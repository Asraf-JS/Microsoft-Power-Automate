import { session, open, capture } from './capture-helpers.mjs';
const context = await session();
const chapter = '04-excel-summary';
const env = 'https://make.powerautomate.com/environments/b3c2cece-31a3-e316-bdc9-540bfc327e87';
const workbook = await open(context, 'https://jsasraf-my.sharepoint.com/:x:/r/personal/asraf_jsasraf_onmicrosoft_com/_layouts/15/Doc.aspx?sourcedoc=%7B9EFE85BD-BB0A-4DBD-A426-94B6FE1829CF%7D&file=TrainingRegister.xlsx&action=default&mobileredirect=true');
await workbook.reload();
await workbook.frameLocator('iframe').first().getByRole('tab', { name: 'Table Design', exact: true }).click();
await capture(workbook, chapter, '04-01-table-name.png');
const page = await open(context, `${env}/create`);
await page.getByText('Instant cloud flow', { exact: true }).click();
await page.getByRole('textbox', { name: 'Flow name', exact: true }).fill('PA - Training register summary');
await page.getByText('Manually trigger a flow', { exact: true }).first().click();
await capture(page, chapter, '04-02-create-flow.png');
await page.getByText('Cancel', { exact: true }).click();
// Reuse the lesson flow. The permitted test has already sent one report to the training account.
await page.goto(`${env}/solutions/~preferred/flows/3608890e-5706-b3fb-4474-aa7b99a2c4bd?v3=true`);
const action = async name => {
  await page.getByRole('button', { name, exact: true }).click();
  await page.waitForTimeout(500);
};
await action('List rows present in a table operation, Excel Online (Business) connector');
await capture(page, chapter, '04-03-list-rows.png');
await action('Select operation, Data Operation connector');
await capture(page, chapter, '04-04-select.png');
await action('Create HTML table operation, Data Operations connector');
await capture(page, chapter, '04-05-html-table.png');
await action('Send an email (V2) operation, Office 365 Outlook connector');
await capture(page, chapter, '04-06-email.png');
await page.locator('[data-automation-id="flow-token flow-input-token-length(...)"]').click();
await page.locator('textarea').first().waitFor();
await capture(page, chapter, '04-07-expression.png');
await page.getByRole('button', { name: 'Close', exact: true }).click();
await page.getByRole('button', { name: 'Collapse', exact: true }).last().click();
await capture(page, chapter, '04-08-full-flow.png');
const mail = context.pages().find(p => p.url().startsWith('https://outlook.cloud.microsoft/mail/')) || await open(context, 'https://outlook.office.com/mail/');
await mail.getByLabel('Search for email, meetings, files and more.', { exact: true }).fill('subject:"[PA TRAINING] Training register summary"');
await mail.getByLabel('Search for email, meetings, files and more.', { exact: true }).press('Enter');
await mail.waitForTimeout(2000);
await mail.getByText('[PA TRAINING] Training register summary', { exact: true }).first().click();
await mail.waitForTimeout(500);
await capture(mail, chapter, '04-09-email-received.png');
process.exit(0);
